# ------------------------------------------------------------------ hello.config path access
_TOKEN = re.compile(r"([^.\[\]]+)|\[([^\]]+)\]")


def cfg_get(cfg: Any, path: str) -> Any:
    """Resolve 'a.b[0].c' in a JSON tree. '[k]' on a list selects index k if numeric, else the element
    whose 'id' == k or whose 'path' ends with '.k' (upgrade effects). Raises KeyError if absent."""
    cur = cfg
    for name, idx in _TOKEN.findall(path):
        key = name or idx
        if isinstance(cur, list):
            if re.fullmatch(r"-?\d+", key):
                cur = cur[int(key)]
                continue
            hit = None
            for el in cur:
                if isinstance(el, dict) and (el.get("id") == key or str(el.get("path", "")).split(".")[-1] == key):
                    hit = el
                    break
            if hit is None:
                raise KeyError(path)
            cur = hit
        elif isinstance(cur, dict):
            cur = cur[key]
        else:
            raise KeyError(path)
    return cur


