_MISS = object()        # cached "path absent"
_MISS_KEY = object()    # not cached yet


class Config:
    """Bound constants: C.NAME. Also C.cfg (raw hello.config), C.base (values at bind, before any
    live update), C.bind_errors (name -> message), C.path(p) for raw config paths."""

    def __init__(self, values: Dict[str, Any], cfg: Dict[str, Any]):
        self.__dict__.update(values)
        self.cfg = cfg
        self.base = dict(values)
        self.bind_errors: Dict[str, str] = {}

    def path(self, p: str, default: Any = None) -> Any:
        """Raw config value at path `p` (cached per path: hello.config never changes after bind; the
        cache is dropped when `cfg` is reassigned). Hot: assess.dps calls it hundreds of times a tick."""
        cfg = self.cfg
        pc = self.__dict__.get("_pcache")
        if pc is None or pc[0] is not cfg:
            pc = self.__dict__["_pcache"] = (cfg, {})
        cache = pc[1]
        v = cache.get(p, _MISS_KEY)
        if v is _MISS_KEY:
            try:
                v = cfg_get(cfg, p)
            except (KeyError, IndexError, TypeError):
                v = _MISS
            cache[p] = v
        return default if v is _MISS else v

    def get(self, name: str, default: Any = None) -> Any:
        return self.__dict__.get(name, default)

    def names(self):
        return [n for n in DEFAULTS]

    def as_dict(self) -> Dict[str, Any]:
        return {n: self.__dict__.get(n) for n in DEFAULTS}

    def __repr__(self) -> str:
        return f"<Config {len(DEFAULTS)} constants, {len(self.bind_errors)} bind errors>"


def _phase_sum(phases, n):
    """Sum of hold_s + shrink_s over phases[0..n-1]."""
    return sum(float(p["hold_s"]) + float(p["shrink_s"]) for p in phases[:max(0, n)])


