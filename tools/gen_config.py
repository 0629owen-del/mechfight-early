#!/usr/bin/env python3
"""Generate the table block of config.py from the plan's section 10 (and two small side tables).

    python3 tools/gen_config.py                 # rewrite the generated block in config.py
    python3 tools/gen_config.py --check         # exit 1 if config.py is out of date
    python3 tools/gen_config.py --plan PATH --hello PATH

Sources (defaults are relative to this repo, i.e. bot/../mechfight-kit/...):
- plan section 10 tables (every row whose first cell is a `CONSTANT`), the IMPL_* paragraph,
  the 8.5 loadout rank table;
- GP "Upgrades by loadout" table (../game-plan.md), mapped from upgrade names to ids with the
  recorded hello (check/stream.jsonl.gz line 1).

Only the block between the BEGIN/END GENERATED markers in config.py is rewritten; the hand-written
bind()/update_live() code around it is kept. Stdlib only; dev-time tool (not shipped in the image).
"""
from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import os
import pprint
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
KIT = os.path.join(os.path.dirname(REPO), "mechfight-kit")
DEF_PLAN = os.path.join(KIT, "docs", "game-plan-v2.md")
DEF_GP = os.path.join(os.path.dirname(REPO), "game-plan.md")
DEF_HELLO = os.path.join(KIT, "check", "stream.jsonl.gz")
CONFIG_PY = os.path.join(REPO, "config.py")

BEGIN = "# --- BEGIN GENERATED by tools/gen_config.py: do not edit by hand ---"
END = "# --- END GENERATED ---"

# Section 16.1 user decisions (2026-11-20/21). The section 10 tables already carry them; the
# generator asserts that and forces these values if a table ever disagrees.
USER_DECISIONS = {
    "ZONE_OUTRANKS_DODGE": "collapse",
    "SWAP_RULE": "rank",
    "ALIVE_LE3_PASSIVE": True,
    "ALIVE2_FIGHT_IF_BEHIND": True,
    "LASER_VIEW_RESPONSE": "gl_only",
    "TLM_DEBUG_CHANNEL": False,
}

# Rows whose default is not a plain scalar.
UPGRADE_FALLBACK_IDS = ["plating", "armor", "servos", "sensors", "capacitor", "reactor", "jets", "gyros", "nanites"]


def _num(s: str):
    s = s.replace("−", "-").strip()
    return float(s) if ("." in s or "e" in s.lower()) else int(s)


def parse_default(name: str, cell: str):
    s = cell.strip().replace("−", "-")
    if name in ("HIT_GUN", "HIT_MORTAR"):
        return [(_num(a), _num(b)) for a, b in re.findall(r"(-?\d+(?:\.\d+)?)\s*→\s*(-?\d+(?:\.\d+)?)", s)]
    if name in ("SOUND_BAND_REP", "PRIOR_SECOND"):
        return {k: _num(v) for k, v in re.findall(r"([a-z_]+)\s+(-?\d+(?:\.\d+)?)", s)}
    if name == "UPGRADE_FALLBACK":
        return list(UPGRADE_FALLBACK_IDS)
    if name == "ENEMY_LIGHTNING_RANGE_MULT":
        return 1.0  # per track (1.0-1.44); this is the global "nothing known" value
    low = s.lower()
    if low.startswith("false"):
        return False
    if low.startswith("true"):
        return True
    if s.startswith('"'):
        return s.split('"')[1]
    m = re.match(r"-?\d+(?:\.\d+)?", s)
    if m:
        return _num(m.group(0))
    return None  # e.g. "computed at `hello`": filled by its owner at hello


def classify(source: str):
    """(kind, cfg_path or None, live flag)."""
    src = source.strip()
    live = "live" in src
    m = re.match(r"CFG\s+`([^`]+)`", src)
    if m:
        return "CFG", m.group(1), live
    if src.startswith("TOGGLE"):
        return "TOGGLE", None, live
    if "DERIVED" in src:
        return "DERIVED", None, live
    if src.startswith("PROTO"):
        return "PROTO", None, live
    if src.startswith("TUNE"):
        return "TUNE", None, live
    if src.lower().startswith("user decision"):
        return "USER", None, live
    if src.startswith("GP"):
        return "GP", None, live
    return "OTHER", None, live


def split_row(line: str):
    cells = [c.strip() for c in line.strip().strip("|").split(" | ")]
    return cells


def parse_plan(text: str):
    start = text.index("\n## 10. ")
    end = text.index("\n## 11. ", start)
    sec = text[start:end]
    rows = {}
    order = []
    section = "10"
    for line in sec.splitlines():
        h = re.match(r"###\s+(10\.\d+)", line)
        if h:
            section = h.group(1)
            continue
        if not line.startswith("| `"):
            continue
        cells = split_row(line)
        if len(cells) < 4:
            continue
        m = re.fullmatch(r"`([A-Z][A-Z0-9_]*)`", cells[0])
        if not m:
            continue
        name = m.group(1)
        if name in rows:
            raise SystemExit(f"duplicate constant {name} in section 10")
        kind, path, live = classify(cells[2])
        rows[name] = {
            "default": parse_default(name, cells[1]),
            "default_text": cells[1],
            "kind": kind,
            "path": path,
            "live": live or "(live" in cells[1],
            "source": cells[2],
            "used_by": cells[3],
            "section": section,
        }
        order.append(name)
    # IMPL_* paragraph
    impl = {}
    for name, val in re.findall(r"`(IMPL_[A-Z_]+)`\s+(-?\d+(?:\.\d+)?)", sec):
        impl[name] = _num(val)
    for name, val in impl.items():
        rows[name] = {"default": val, "default_text": str(val), "kind": "IMPL", "path": None, "live": False,
                      "source": "IMPL structural constant", "used_by": "", "section": "10.16"}
        order.append(name)
    return rows, order


def parse_rank_table(text: str):
    start = text.index("### 8.5 ")
    end = text.index("\n### 8.6", start)
    out = {}
    for line in text[start:end].splitlines():
        if not line.startswith("| ") or line.startswith("| ---") or line.startswith("| Loadout"):
            continue
        cells = split_row(line)
        if len(cells) != 4:
            continue
        try:
            vals = {"LIGHTNING": _num(cells[1]), "LASER": _num(cells[2]), "MIXED": _num(cells[3])}
        except ValueError:
            continue
        label = cells[0]
        if label.startswith("L alone"):
            keys = ["L", "Z"]
        elif label.endswith("alone"):
            keys = [label.split()[0]]
        else:
            keys = [label]
        for k in keys:
            out[k] = vals
    return out


def parse_gp_upgrades(gp_text: str, hello_cfg: dict):
    name_to_id = {u["name"]: u["id"] for u in hello_cfg["upgrades"]}
    # GP uses short names ("Superconductor", "Plating"); match on the first word / prefix
    def resolve(n):
        n = n.strip()
        for full, uid in name_to_id.items():
            if full == n or full.split()[-1].lower() == n.split()[-1].lower() or full.lower().startswith(n.lower()):
                return uid
        raise SystemExit(f"GP upgrade name {n!r} not in hello.config.upgrades")
    keymap = {"Gun + lightning": "GL", "Gun + laser": "GZ", "Laser + lightning": "ZL", "Only mech upgrades offered": "MECH"}
    i = gp_text.index("**Upgrades by loadout:**")
    out = {}
    for line in gp_text[i:].splitlines()[1:]:
        if line.startswith("## "):
            break
        if not line.startswith("| ") or line.startswith("| ---") or line.startswith("| Loadout"):
            continue
        cells = split_row(line)
        if cells[0] in keymap:
            out[keymap[cells[0]]] = [resolve(x) for x in cells[1].split("→")]
    if set(out) != set(keymap.values()):
        raise SystemExit(f"GP upgrade table incomplete: {sorted(out)}")
    return out


def build_block(plan_path, gp_path, hello_path):
    with open(plan_path, encoding="utf-8") as f:
        text = f.read()
    with open(gp_path, encoding="utf-8") as f:
        gp_text = f.read()
    with gzip.open(hello_path, "rt") as f:
        hello = json.loads(f.readline())
    rows, order = parse_plan(text)
    for k, v in USER_DECISIONS.items():
        if k not in rows:
            raise SystemExit(f"user-decision constant {k} missing from section 10")
        if rows[k]["default"] != v:
            print(f"note: {k} table default {rows[k]['default']!r} overridden by user decision {v!r}", file=sys.stderr)
            rows[k]["default"] = v
    unparsed = [n for n in order if rows[n]["default"] is None]
    defaults = {n: rows[n]["default"] for n in order}
    sources = {n: (rows[n]["kind"], rows[n]["source"]) for n in order}
    cfg_paths = {n: rows[n]["path"] for n in order if rows[n]["kind"] == "CFG"}
    live = sorted(n for n in order if rows[n]["live"])
    sections = {n: rows[n]["section"] for n in order}
    rank = parse_rank_table(text)
    upgrades = parse_gp_upgrades(gp_text, hello["config"])
    digest = hashlib.sha256(text[text.index("\n## 10. "):text.index("\n## 11. ")].encode()).hexdigest()[:16]
    pp = lambda o: pprint.pformat(o, width=110, sort_dicts=False)
    parts = [
        BEGIN,
        f"# plan: docs/game-plan-v2.md section 10 (sha256[:16] {digest}); {len(order)} constants;",
        f"# None defaults (filled at hello by their owner): {', '.join(unparsed) or 'none'}",
        f"PLAN_SECTION10_SHA = {digest!r}",
        "",
        "# name -> default (the recorded-hello value for CFG rows; GP/TUNE values otherwise)",
        f"DEFAULTS = {pp(defaults)}",
        "",
        "# name -> (kind, source text). kind: CFG, DERIVED, TOGGLE, TUNE, GP, PROTO, USER, IMPL, OTHER",
        f"SOURCES = {pp(sources)}",
        "",
        "# CFG rows: name -> path in hello.config ('a.b[0].c'; '[key]' on a list selects by id / path suffix)",
        f"CFG_PATHS = {pp(cfg_paths)}",
        "",
        "# rows marked live in the plan (recomputed each tick by update_live from self stats)",
        f"LIVE = {pp(live)}",
        "",
        f"SECTIONS = {pp(sections)}",
        "",
        "# 8.5 loadout rank: key = held-weapon letters (G gun, Z laser, L lightning, M mortar), 'empty'",
        f"LOADOUT_RANK = {pp(rank)}",
        "",
        "# GP 'Upgrades by loadout' (R14.1), ids from hello.config.upgrades",
        f"UPGRADE_PRIORITY = {pp(upgrades)}",
        "",
        f"USER_DECISIONS = {pp(USER_DECISIONS)}",
        END,
    ]
    return "\n".join(parts) + "\n"


def splice(existing: str, block: str) -> str:
    if BEGIN in existing and END in existing:
        a = existing.index(BEGIN)
        b = existing.index(END) + len(END)
        rest = existing[b:]
        if rest.startswith("\n"):
            rest = rest[1:]
        return existing[:a] + block + rest
    raise SystemExit("config.py has no generated-block markers")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--plan", default=DEF_PLAN)
    ap.add_argument("--gp", default=DEF_GP)
    ap.add_argument("--hello", default=DEF_HELLO)
    ap.add_argument("--config", default=CONFIG_PY)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    block = build_block(a.plan, a.gp, a.hello)
    with open(a.config, encoding="utf-8") as f:
        old = f.read()
    new = splice(old, block)
    if a.check:
        if new != old:
            print("config.py is out of date: run tools/gen_config.py", file=sys.stderr)
            return 1
        print("config.py is up to date")
        return 0
    if new != old:
        with open(a.config, "w", encoding="utf-8") as f:
            f.write(new)
        print(f"wrote {a.config}")
    else:
        print("config.py unchanged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
